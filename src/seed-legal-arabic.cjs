async function run() {
  const client = new MongoClient(process.env.DATABASE_URL);
  try {
    await client.connect();
    const db = client.db();
    
    // Update Privacy Policy
    const privacyPolicy = await db.collection('privacy-policies').findOne({});
    if (privacyPolicy) {
      const updatedSections = privacyPolicy.sections.map((section, index) => {
        return {
          ...section,
          heading: {
            ...section.heading,
            ar: PRIVACY_SECTIONS_AR[index] ? PRIVACY_SECTIONS_AR[index].heading : section.heading.en
          },
          content: {
            ...section.content,
            ar: PRIVACY_SECTIONS_AR[index] ? PRIVACY_SECTIONS_AR[index].content : section.content.en
          }
        };
      });

      await db.collection('privacy-policies').updateOne(
        { _id: privacyPolicy._id },
        {
          $set: {
            'pageTitle.ar': 'سياسة الخصوصية',
            sections: updatedSections
          }
        }
      );
      console.log('Privacy Policy updated with Arabic translations.');
    }

    // Update Terms of Service
    const termsService = await db.collection('terms-of-services').findOne({});
    if (termsService) {
      const updatedSections = termsService.sections.map((section, index) => {
        return {
          ...section,
          heading: {
            ...section.heading,
            ar: TERMS_SECTIONS_AR[index] ? TERMS_SECTIONS_AR[index].heading : section.heading.en
          },
          content: {
            ...section.content,
            ar: TERMS_SECTIONS_AR[index] ? TERMS_SECTIONS_AR[index].content : section.content.en
          }
        };
      });

      await db.collection('terms-of-services').updateOne(
        { _id: termsService._id },
        {
          $set: {
            'pageTitle.ar': 'شروط الخدمة',
            sections: updatedSections
          }
        }
      );
      console.log('Terms of Service updated with Arabic translations.');
    }

  } catch (error) {
    console.error('Error:', error);
  } finally {
    await client.close();
  }
}

run();
